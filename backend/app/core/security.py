"""
Authentication and authorization utilities.

Per-user session access control is enforced here.
JWT tokens carry the username as 'sub'; all resource ownership
checks compare against this value server-side.
"""
from __future__ import annotations

import logging
from datetime import datetime, timedelta
from typing import Optional
from urllib.parse import quote

from fastapi import Depends, HTTPException, status
from fastapi.security import OAuth2PasswordBearer
from jose import JWTError, jwt

from app.core.config import settings

logger = logging.getLogger("rag_app")

oauth2_scheme = OAuth2PasswordBearer(tokenUrl="/api/login")


def create_access_token(data: dict) -> str:
    payload = data.copy()
    payload["exp"] = datetime.utcnow() + timedelta(
        minutes=settings.ACCESS_TOKEN_EXPIRE_MINUTES
    )
    return jwt.encode(payload, settings.SECRET_KEY, algorithm=settings.ALGORITHM)


def verify_token(token: str = Depends(oauth2_scheme)) -> str:
    """Dependency: decode JWT and return the username ('sub')."""
    exc = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Invalid or expired token",
        headers={"WWW-Authenticate": "Bearer"},
    )
    try:
        payload = jwt.decode(
            token, settings.SECRET_KEY, algorithms=[settings.ALGORITHM]
        )
        username: Optional[str] = payload.get("sub")
        if not username:
            raise exc
        return username
    except JWTError:
        raise exc


def require_session_owner(session_id: str, user: str) -> None:
    """
    Enforce per-user session ownership.

    In 'open' doc access mode every authenticated user can see every session
    (single-tenant dev mode). In 'user' mode, sessions are scoped to the
    creator's username prefix.

    This is a server-side gate — the session_id pattern `sess_<user>_<rand>`
    is created by the backend when DOC_ACCESS_MODE='user'.
    For the default 'open' mode this is a no-op so existing behaviour is preserved.
    """
    if settings.DOC_ACCESS_MODE == "open":
        return
    # Session IDs use the URL-safe username prefix generated by the frontend.
    owner_prefix = f"sess_{quote(user, safe='')}_"
    if not session_id.startswith(owner_prefix):
        logger.warning(
            "Access control violation: user=%s attempted to access session=%s",
            user, session_id,
        )
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You do not have access to this session.",
        )


def require_document_access(filename: str, user: str, accessible_docs: list) -> None:
    """
    Enforce per-user document access control.
    'open' mode skips the check; 'user' mode requires the doc in the user's list.
    """
    if settings.DOC_ACCESS_MODE == "open":
        return
    if filename.lower() not in [d.lower() for d in accessible_docs]:
        logger.warning(
            "Document access denied: user=%s filename=%s", user, filename
        )
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=f"You do not have access to document '{filename}'.",
        )
